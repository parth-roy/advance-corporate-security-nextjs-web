export function generateServiceMeta(
  service: ACSService,
  cityName?: string,
): { title: string; description: string } {
  if (!cityName) {
    return {
      title: `${service.name} | Advance Corporate Security`,
      description: service.description,
    };
  }
  return {
    title: service.metaTitleTemplate.replace(/\[City\]/g, cityName),
    description: service.metaDescTemplate.replace(/\[City\]/g, cityName),
  };
}
