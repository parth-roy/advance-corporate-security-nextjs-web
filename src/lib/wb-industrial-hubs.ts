/**
 * Returns up to 4 industrial hubs nearest to the given city slug.
 */
export function getWBHubsForCity(citySlug: string): WBIndustrialHub[] {
  return WB_INDUSTRIAL_HUBS.filter((hub) =>
    hub.nearestCities.includes(citySlug)
  ).slice(0, 4);
}

